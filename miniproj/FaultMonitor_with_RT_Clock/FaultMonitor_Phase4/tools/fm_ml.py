#!/usr/bin/env python3
"""
fm_ml.py -- the "lightweight machine-learning approach", offline.
Owner: Arfan (model) with Abhishek (data).

Input: a CSV recorded with  python fm_dump.py --port COM5 stream -t 600
while a campaign runs in parallel, so every window carries the ground-
truth label the firmware attaches (L:<comp>:<fault>, 255 = normal).

Trains and compares, on the same windows the on-chip localizers saw:
  1. Isolation Forest   -- unsupervised anomaly DETECTION (normal vs not),
                           learns from normal windows only, like the
                           on-chip baseline
  2. Decision tree      -- supervised LOCALIZATION (which component),
                           small enough to export as if/else C code for
                           the MCU (--export-c)
and prints them next to the on-chip rule-based (R:) and statistical (Q:)
verdicts found in the same lines.

  pip install pandas scikit-learn
  python fm_ml.py sig_stream.csv [--export-c fm_tree.c]
"""
import argparse
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--export-c", help="write the decision tree as C")
    ap.add_argument("--max-depth", type=int, default=5)
    args = ap.parse_args()
    try:
        import pandas as pd
        from sklearn.ensemble import IsolationForest
        from sklearn.metrics import classification_report, accuracy_score
        from sklearn.model_selection import train_test_split
        from sklearn.tree import DecisionTreeClassifier, export_text
    except ImportError:
        sys.exit("pip install pandas scikit-learn")

    df = pd.read_csv(args.csv)
    if "mode" in df.columns:
        df = df[df["mode"] == 2]                           # monitoring windows only
    feats = [c for c in df.columns if c.startswith("c") and "_" in c and c[1].isdigit()]
    feats += [c for c in ("comm_err", "periph_err") if c in df.columns]
    X = df[feats].fillna(0).astype(float)
    # time features in cycles, per window length -> fractions
    for c in X.columns:
        if c.endswith(("_cpu", "_max_slice", "_max_gap")):
            X[c] = X[c] / df["t_len"]
    y_comp = df["label_comp"].fillna(255).astype(int)
    normal = y_comp == 255
    print(f"{len(df)} windows, {normal.sum()} normal, {(~normal).sum()} faulty, {len(feats)} features")

    # 1. Isolation Forest: detection only
    iso = IsolationForest(n_estimators=100, contamination="auto", random_state=0)
    iso.fit(X[normal])
    pred_anom = iso.predict(X) == -1
    tp = (pred_anom & ~normal).sum(); fp = (pred_anom & normal).sum()
    fn = (~pred_anom & ~normal).sum()
    print(f"\nIsolation Forest  detection rate {tp / max(1, tp + fn):.1%}, "
          f"false-positive rate {fp / max(1, normal.sum()):.1%}")

    # 2. Decision tree: localization (normal = class 255)
    Xtr, Xte, ytr, yte = train_test_split(X, y_comp, test_size=0.3, random_state=0,
                                          stratify=y_comp if y_comp.value_counts().min() > 1 else None)
    tree = DecisionTreeClassifier(max_depth=args.max_depth, random_state=0).fit(Xtr, ytr)
    yp = tree.predict(Xte)
    print(f"\nDecision tree (depth {args.max_depth}) accuracy {accuracy_score(yte, yp):.1%}")
    print(classification_report(yte, yp, zero_division=0))

    # 3. on-chip localizers on the same windows
    for k, name in (("rule", "rule-based (on chip)"), ("stat", "statistical (on chip)")):
        if f"{k}_comp" in df.columns:
            flagged = df[f"{k}_comp"] != 255
            hit = flagged & ~normal
            acc = (df.loc[hit, f"{k}_comp"] == y_comp[hit]).mean() if hit.any() else float("nan")
            print(f"{name:24} flags {hit.sum()} of {(~normal).sum()} faulty windows, "
                  f"{(flagged & normal).sum()} normal ones; localization {acc:.1%}")
    print("\nNote: the on-chip localizers act on the FIRST faulty window and then recover,")
    print("so per-window counts understate them; use fm_metrics.py for per-trial numbers.")

    print("\nTree rules:\n" + export_text(tree, feature_names=list(X.columns)))
    if args.export_c:
        export_c(tree, list(X.columns), args.export_c)


def export_c(tree, names, path):
    t = tree.tree_
    out = ["/* generated by fm_ml.py: decision tree localizer.",
           " * Features are fractions of the window (cpu, slice, gap) or counts. */",
           "#include <stdint.h>", "", "uint8_t fm_tree_localize(const float *x)", "{"]

    def rec(node, depth):
        ind = "    " * depth
        if t.children_left[node] == -1:
            cls = tree.classes_[t.value[node][0].argmax()]
            out.append(f"{ind}return {int(cls)};")
            return
        out.append(f"{ind}if (x[{t.feature[node]}] <= {t.threshold[node]:.6f}f) {{  /* {names[t.feature[node]]} */")
        rec(t.children_left[node], depth + 1)
        out.append(f"{ind}}} else {{")
        rec(t.children_right[node], depth + 1)
        out.append(f"{ind}}}")
    rec(0, 1)
    out.append("}")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"saved {path}")


if __name__ == "__main__":
    main()
